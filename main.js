/* ─────────────────────────────────────
   THREE.JS — 3D DNA HELIX
   ───────────────────────────────────── */
let scene, camera, renderer, dnaGroup, particleSystem;

function initThreeJS() {
  const canvas = $('dna-canvas');
  if (!canvas) return;

  scene = new THREE.Scene();
  // Transparent background — page pearl-white shows through

  const cw = canvas.clientWidth || window.innerWidth * 0.55;
  const ch = canvas.clientHeight || window.innerHeight;
  camera = new THREE.PerspectiveCamera(55, cw / ch, 0.1, 1000);
  camera.position.set(0, 0, 28);

  try {
    renderer = new THREE.WebGLRenderer({ canvas, antialias: true, alpha: true });
  } catch (e) {
    console.warn('WebGL not available');
    canvas.style.display = 'none';
    return;
  }
  renderer.setSize(cw, ch);
  renderer.setPixelRatio(Math.min(window.devicePixelRatio, 2));
  renderer.setClearColor(0x000000, 0);

  // ── Lights ──
  scene.add(new THREE.AmbientLight(0xffffff, 0.7));

  const dirLight = new THREE.DirectionalLight(0xffffff, 0.9);
  dirLight.position.set(10, 10, 15);
  scene.add(dirLight);

  const blueLight = new THREE.PointLight(0x3B82F6, 1.2, 60);
  blueLight.position.set(-12, 8, 12);
  scene.add(blueLight);

  const lavLight = new THREE.PointLight(0xA78BFA, 0.9, 60);
  lavLight.position.set(12, -8, 12);
  scene.add(lavLight);

  // ── Build DNA ──
  buildDNA();
  buildParticles();

  // ── Render loop ──
  function animate() {
    requestAnimationFrame(animate);
    if (dnaGroup) {
      dnaGroup.rotation.y += 0.004;
      // Mouse parallax
      dnaGroup.rotation.x += (state.mouse.y * 0.15 - dnaGroup.rotation.x) * 0.02;
      dnaGroup.position.x += ((state.mouse.x * 2) - dnaGroup.position.x) * 0.02;
    }
    if (particleSystem) {
      particleSystem.rotation.y += 0.0003;
      particleSystem.rotation.x += 0.0001;
    }
    renderer.render(scene, camera);
  }
  animate();
}

function buildDNA() {
  dnaGroup = new THREE.Group();

  const R = 2.8;          // helix radius
  const H = 36;           // total height
  const turns = 3.5;
  const N = 140;           // points per strand
  const sphereGeo = new THREE.SphereGeometry(0.25, 12, 12);

  const mat1 = new THREE.MeshStandardMaterial({
    color: 0x3B82F6, roughness: 0.3, metalness: 0.1,
    emissive: 0x1e40af, emissiveIntensity: 0.15
  });
  const mat2 = new THREE.MeshStandardMaterial({
    color: 0xA78BFA, roughness: 0.3, metalness: 0.1,
    emissive: 0x6d28d9, emissiveIntensity: 0.15
  });
  const barMat = new THREE.MeshStandardMaterial({
    color: 0x22D3EE, roughness: 0.4, metalness: 0.05,
    emissive: 0x0891b2, emissiveIntensity: 0.2,
    transparent: true, opacity: 0.65
  });

  for (let i = 0; i < N; i++) {
    const t = i / N;
    const angle = t * Math.PI * 2 * turns;
    const y = (t - 0.5) * H;

    // Strand 1
    const x1 = Math.cos(angle) * R;
    const z1 = Math.sin(angle) * R;
    const s1 = new THREE.Mesh(sphereGeo, mat1);
    s1.position.set(x1, y, z1);
    dnaGroup.add(s1);

    // Strand 2 (π offset)
    const x2 = Math.cos(angle + Math.PI) * R;
    const z2 = Math.sin(angle + Math.PI) * R;
    const s2 = new THREE.Mesh(sphereGeo, mat2);
    s2.position.set(x2, y, z2);
    dnaGroup.add(s2);

    // Base pair every 4th node
    if (i % 4 === 0) {
      const dx = x2 - x1;
      const dz = z2 - z1;
      const dist = Math.sqrt(dx * dx + dz * dz);
      const barGeo = new THREE.CylinderGeometry(0.06, 0.06, dist, 6);
      const bar = new THREE.Mesh(barGeo, barMat);
      bar.position.set((x1 + x2) / 2, y, (z1 + z2) / 2);
      // Align cylinder (Y-axis default) to point from s1 → s2
      const dir = new THREE.Vector3(dx, 0, dz).normalize();
      const quat = new THREE.Quaternion().setFromUnitVectors(
        new THREE.Vector3(0, 1, 0), dir
      );
      bar.quaternion.copy(quat);
      dnaGroup.add(bar);
    }
  }

  dnaGroup.position.set(0, 0, 0);
  scene.add(dnaGroup);
}

function buildParticles() {
  const count = 180;
  const positions = new Float32Array(count * 3);
  const colors = new Float32Array(count * 3);
  const palette = [
    new THREE.Color(0x3B82F6),
    new THREE.Color(0xA78BFA),
    new THREE.Color(0x22D3EE)
  ];

  for (let i = 0; i < count; i++) {
    positions[i * 3]     = (Math.random() - 0.5) * 70;
    positions[i * 3 + 1] = (Math.random() - 0.5) * 50;
    positions[i * 3 + 2] = (Math.random() - 0.5) * 40;
    const c = palette[Math.floor(Math.random() * 3)];
    colors[i * 3]     = c.r;
    colors[i * 3 + 1] = c.g;
    colors[i * 3 + 2] = c.b;
  }

  const geo = new THREE.BufferGeometry();
  geo.setAttribute('position', new THREE.BufferAttribute(positions, 3));
  geo.setAttribute('color', new THREE.BufferAttribute(colors, 3));

  const mat = new THREE.PointsMaterial({
    size: 0.12,
    vertexColors: true,
    transparent: true,
    opacity: 0.45,
    sizeAttenuation: true
  });

  particleSystem = new THREE.Points(geo, mat);
  scene.add(particleSystem);
}

/* ─────────────────────────────────────
   EVENT LISTENERS
   ───────────────────────────────────── */
function setupEvents() {
  // Start button
  $('start-btn').addEventListener('click', startPresentation);

  // Timer controls
  $('timer-pause-btn').addEventListener('click', togglePause);
  $('timer-reset-btn').addEventListener('click', resetTimer);

  // Keyboard navigation
  document.addEventListener('keydown', (e) => {
    // Close card on Escape
    if (e.key === 'Escape' && state.cardOpen) {
      closeCard();
      return;
    }
    if (!state.presentationStarted) return;
    // Don't nav while typing
    if (e.target.tagName === 'INPUT' || e.target.tagName === 'TEXTAREA') return;

    switch (e.key) {
      case 'ArrowRight':
      case 'ArrowDown':
        e.preventDefault();
        nextSection();
        break;
      case 'ArrowLeft':
      case 'ArrowUp':
        e.preventDefault();
        prevSection();
        break;
      case 'Home':
        e.preventDefault();
        goToSection(0);
        break;
      case 'End':
        e.preventDefault();
        goToSection(state.totalSections - 1);
        break;
    }
  });

  // Mouse for 3D parallax
  document.addEventListener('mousemove', (e) => {
    state.mouse.x = (e.clientX / window.innerWidth - 0.5) * 2;
    state.mouse.y = (e.clientY / window.innerHeight - 0.5) * 2;
  });

  // Resize
  window.addEventListener('resize', () => {
    if (!camera || !renderer) return;
    const canvas = $('dna-canvas');
    const cw = canvas.clientWidth || window.innerWidth * 0.55;
    const ch = canvas.clientHeight || window.innerHeight;
    camera.aspect = cw / ch;
    camera.updateProjectionMatrix();
    renderer.setSize(cw, ch);
  });

  // Scroll tracking via IntersectionObserver
  const slides = document.querySelectorAll('.slide');
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting && entry.intersectionRatio >= 0.4) {
        const idx = parseInt(entry.target.dataset.index, 10);
        if (!isNaN(idx)) {
          state.currentSection = idx;
          updateNav();
        }
      }
    });
  }, { threshold: 0.4 });
  slides.forEach(s => observer.observe(s));

  // Card overlay click-outside
  $('card-overlay').addEventListener('click', (e) => {
    if (e.target === $('card-overlay')) closeCard();
  });
}

