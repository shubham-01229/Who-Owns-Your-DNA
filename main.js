const $ = (id) => document.getElementById(id);

/* ─────────────────────────────────────
   TIMER
   ───────────────────────────────────── */
function formatTime(ms) {
  const totalSec = Math.floor(ms / 1000);
  const h = Math.floor(totalSec / 3600);
  const m = Math.floor((totalSec % 3600) / 60);
  const s = totalSec % 60;
  const mm = String(m).padStart(2, '0');
  const ss = String(s).padStart(2, '0');
  return h > 0 ? `${h}:${mm}:${ss}` : `${mm}:${ss}`;
}

function tickTimer() {
  if (state.timerStatus === 'running') {
    state.elapsed = state.pausedElapsed + (performance.now() - state.startTimestamp);
    $('timer-display').textContent = formatTime(state.elapsed);
  }
  state.timerRAF = requestAnimationFrame(tickTimer);
}

function startPresentation() {
  if (state.presentationStarted) return;
  state.presentationStarted = true;
  state.timerStatus = 'running';
  state.startTimestamp = performance.now();
  state.elapsed = 0;
  state.pausedElapsed = 0;

  $('start-overlay').classList.add('hidden');
  $('navbar').classList.remove('hidden');
  $('progress-bar').classList.remove('hidden');
  $('presentation').classList.remove('hidden');
  $('nav-hints').classList.remove('hidden');

  tickTimer();
  goToSection(0);
}

function togglePause() {
  const statusEl = $('timer-status');
  const btnEl = $('timer-pause-btn');
  if (state.timerStatus === 'running') {
    state.timerStatus = 'paused';
    state.pausedElapsed = state.elapsed;
    statusEl.textContent = 'PAUSED';
    statusEl.classList.add('paused');
    btnEl.textContent = '▶';
  } else if (state.timerStatus === 'paused') {
    state.timerStatus = 'running';
    state.startTimestamp = performance.now();
    statusEl.textContent = 'LIVE';
    statusEl.classList.remove('paused');
    btnEl.textContent = '⏸';
  }
}

function resetTimer() {
  if (!confirm('Reset the presentation timer to 00:00?')) return;
  state.timerStatus = 'paused';
  state.elapsed = 0;
  state.pausedElapsed = 0;
  state.startTimestamp = 0;
  $('timer-display').textContent = '00:00';
  $('timer-status').textContent = 'RESET';
  $('timer-status').classList.add('paused');
  $('timer-pause-btn').textContent = '▶';
}

/* ─────────────────────────────────────
   NAVIGATION
   ───────────────────────────────────── */
function goToSection(index) {
  if (index < 0 || index >= state.totalSections) return;
  state.currentSection = index;
  const slide = $(`slide-${index + 1}`);
  if (slide) slide.scrollIntoView({ behavior: 'smooth' });
  updateNav();
}
function nextSection() { goToSection(state.currentSection + 1); }
function prevSection() { goToSection(state.currentSection - 1); }

// Expose globally for onclick handlers in HTML
window.goToSection = goToSection;
window.nextSection = nextSection;
window.prevSection = prevSection;

